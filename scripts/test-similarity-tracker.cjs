const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../assets/similarity-tracker.js'), 'utf8');
const store = new Map();
function load(storage = {getItem: k => store.get(k) || null, setItem: (k, v) => store.set(k,v)}) {
  const window = {localStorage: storage};
  vm.runInNewContext(source, {window});
  return window.SFI_TRACKER;
}
const plain = value => JSON.parse(JSON.stringify(value));
